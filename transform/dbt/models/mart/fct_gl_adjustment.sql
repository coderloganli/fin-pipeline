-- The adjustment fact, the same shape as fct_gl_entry and deliberately so: an adjustment
-- is attributed by the same three point-in-time joins, converted with the rate in force
-- on its own accounting date, and rounded at the line. What it adds is `adjusts_entry_id`
-- - which line it revises - and `adjustment_type`, which says whether it amends the
-- period's figure or restates it.
--
-- A table of its own rather than rows of fct_gl_entry because gate 3 groups by doc_id and
-- requires debits to equal credits. An adjustment is a single-sided delta against a
-- voucher that already balanced, so folding it in would turn that gate red on a correct
-- ledger. See docs/adr/0042.
--
-- `adjusts_entry_id` is carried and not enforced. An adjustment can legitimately point at
-- an entry outside the loaded window, and a gate that fires on a correct backfill is one
-- people learn to ignore. It is a trail to follow, not a constraint.
